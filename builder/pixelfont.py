# rows below the baseline
DESCENDERS = {
    "g": (".####|#...#|#...#|#...#|#...#|.####|....#|.###.", 2),
    "j": ("..#|...|.##|..#|..#|..#|..#|..#|#.#|.#.", 2),
    "p": ("####.|#...#|#...#|#...#|#...#|####.|#....|#....", 2),
    "q": (".####|#...#|#...#|#...#|#...#|.####|....#|....#", 2),
    "y": ("#...#|#...#|#...#|#...#|#...#|.####|....#|.###.", 2),
    ",": ("##|##|.#|#.", 2),
    ";": ("##|##|..|..|##|##|.#|#.", 2),
}


def glyph(ch):
    """Return a bool array positioned in rows: 0 is the top of a capital."""
    rows, below = DESCENDERS.get(ch, (_.get(ch), 0))
    rows = rows.split("|")
    top = CAP + below - len(rows)
    a = np.zeros((CAP + 2, len(rows[0])), dtype=bool)
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            a[top + y, x] = c == "#"
    return a


def has(ch):
    return ch in _ or ch in DESCENDERS


def word(text, gap=1):
    """Two letters side by side, for the double-letter glyphs."""
    parts = [glyph(c) for c in text if c != " "]
    w = sum(p.shape[1] for p in parts) + gap * (len(parts) - 1)
    out = np.zeros((CAP + 2, w), dtype=bool)
    x = 0
    for p in parts:
        out[:, x:x + p.shape[1]] = p
        x += p.shape[1] + gap
    return out
